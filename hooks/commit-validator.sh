#!/bin/bash
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# Commit Validator Hook — enforces commit hygiene
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# Trigger: PreToolUse on Bash
# Purpose: Two gates on git commit commands:
#   1. BLOCK AI attribution (Co-Authored-By: Claude, etc.) — exit 2
#   2. WARN on non-conventional commit format — exit 0 with message
#
# Only validates when commit message is confidently extractable.
# If message can't be parsed (interactive, complex heredoc), allows through.
#
# Exit 0 = allow, Exit 2 = block with message
#
# Note: set -e intentionally omitted — grep returns 1 on no-match,
# which is expected control flow in hook scripts.

# Windows jq compat — strip \r from output (see lib/platform.sh)
[[ "${OSTYPE:-}" == msys* || "${OSTYPE:-}" == mingw* ]] && jq() { local _rc; command jq "$@" | tr -d '\r'; _rc=${PIPESTATUS[0]}; return "$_rc"; }

INPUT=$(cat)
_HOOK_START=$SECONDS
_CV_TMPDIR="${TMPDIR:-/tmp}"

_cv_log() {
  local dur=$(( (SECONDS - _HOOK_START) * 1000 ))
  printf '%s|commit-validator|%s|%s\n' "$(date +%s)" "$dur" "$1" >> "${_CV_TMPDIR}/forge-session-log-${PPID}" 2>/dev/null
  printf '%s|commit-validator|%s|%s\n' "$(date +%s)" "$dur" "$1" >> "$HOME/.claude/hook-telemetry.log" 2>/dev/null
}

COMMAND=$(echo "$INPUT" | jq -r '.tool_input.command // empty')

# Only act on git commit commands
echo "$COMMAND" | grep -q 'git commit' || { _cv_log allow; exit 0; }

# ── Gate 1: Block AI attribution ──────────────────────────────
# Check the full command for attribution patterns (catches -m, heredoc, etc.)
if echo "$COMMAND" | grep -qiE 'Co-Authored-By:\s*(Claude|Anthropic)|Generated with (Claude|Claude Code)'; then
  echo "BLOCKED: Commit contains AI attribution. Remove any 'Co-Authored-By: Claude', 'Generated with Claude Code', or similar lines. This project does not use AI attribution in commits." >&2
  _cv_log block; exit 2
fi

# ── Gate 2: Warn on non-conventional commit format ────────────
# Extract commit message — only from patterns we can confidently parse.
# If we can't extract it, allow through (no false positives).
MSG=""

# Try -m "..." (double quotes)
if [ -z "$MSG" ]; then
  MSG=$(echo "$COMMAND" | grep -oE '\-m "([^"]*)"' | head -1 | sed 's/^-m "//;s/"$//')
fi

# Try -m '...' (single quotes)
if [ -z "$MSG" ]; then
  MSG=$(echo "$COMMAND" | grep -oE "\-m '([^']*)'" | head -1 | sed "s/^-m '//;s/'$//")
fi

# Heredoc format: best-effort extraction only. Gate 1 (AI attribution) scans
# the full command string regardless, so heredocs are always covered for the
# critical case. Gate 2 (conventional format) may miss heredocs — acceptable.
if [ -z "$MSG" ]; then
  MSG=$(echo "$COMMAND" | awk '/<<.*EOF/{found=1; next} found && /^[[:space:]]*[a-zA-Z]/{print; exit}' | sed 's/^[[:space:]]*//')
fi

# Can't extract message — allow through
[ -z "$MSG" ] && { _cv_log allow; exit 0; }

# Get first line only (for multi-line messages)
FIRST_LINE=$(echo "$MSG" | head -1)

# Skip merge commits and reverts generated by git itself
echo "$FIRST_LINE" | grep -qE '^(Merge |Revert ")' && { _cv_log allow; exit 0; }

# Check conventional commit format
if ! echo "$FIRST_LINE" | grep -qE '^(feat|fix|chore|docs|test|refactor|style|perf|ci|build|revert)(\(.+\))?(!)?\s*:'; then
  # Read persona for message tone
  PROFILE="$HOME/.claude/profile.json"
  WORKFLOW="advanced"
  if [ -f "$PROFILE" ]; then
    WORKFLOW=$(jq -r '.axes.workflow // "advanced"' "$PROFILE" 2>/dev/null)
  fi

  if [ "$WORKFLOW" = "simplified" ]; then
    WARNING="The commit message needs to follow a specific format. It should start with a type like feat: or fix: followed by what changed. Example: feat(auth): add login flow"
  else
    WARNING="Commit message does not follow conventional commit format. Expected: <type>(<scope>): <description> — where type is one of: feat, fix, chore, docs, test, refactor, style, perf, ci, build, revert. Got: \"${FIRST_LINE}\""
  fi

  # Warn but allow (exit 0) — Claude sees the warning and self-corrects
  jq -n --arg warning "$WARNING" '{
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      additionalContext: ("WARNING: " + $warning)
    }
  }'
fi

_cv_log allow; exit 0